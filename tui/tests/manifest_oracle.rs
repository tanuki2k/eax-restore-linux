#[test]
fn content_checks_match() {
    let tmp = tempfile::tempdir().unwrap();
    let d = tmp.path();
    let contents: [(&str, &[u8]); 9] = [
        ("dsoal", b"MZ\x90\0 some DSOAL build \0"),
        ("soft", b"MZ\0OpenAL Soft 1.23\0"),
        ("soft-env", b"MZ\0ALSOFT_LOGLEVEL\0"),
        ("creative", b"MZ\0Creative Labs router\0"),
        ("builtin", b"MZ\0Wine builtin DLL\0"),
        ("placeholder", b"MZ\0Wine placeholder DLL\0"),
        (
            "generated",
            b"# Auto-generated by EAX Restore Script\n[general]\n",
        ),
        ("handmade", b"[general]\nhrtf=true\n"),
        ("empty", b""),
    ];
    let names = [
        "dsound.dll",
        "DSOUND.DLL",
        "dsoal-aldrv.dll",
        "OpenAL32.dll",
        "eax.dll",
        "EAXUnified.dll",
        "alsoft.ini",
        "other.dll",
    ];
    let mut paths = Vec::new();
    for (kind, bytes) in contents {
        for name in names {
            let path = d.join(kind).join(name);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, bytes).unwrap();
            paths.push(path.display().to_string());
        }
    }
    // A link to one of ours, a folder with the name, and nothing at all.
    std::fs::create_dir_all(d.join("odd/dir/dsound.dll")).unwrap();
    symlink(d.join("dsoal/dsound.dll"), d.join("odd/dsound.dll")).unwrap();
    for odd in [
        "odd/dsound.dll",
        "odd/dir/dsound.dll",
        "odd/missing/eax.dll",
    ] {
        paths.push(d.join(odd).display().to_string());
    }

    type Check = fn(&Path) -> bool;
    let checks: [(&str, Check); 3] = [
        ("looks_like_our_file", files::looks_like_our_file),
        ("is_genuine_dll", files::is_genuine_dll),
        ("is_openal_soft_dll", files::is_openal_soft_dll),
    ];
    for (function, rust_fn) in checks {
        // The script's is_genuine_dll takes a folder with a DLL's name for a
        // genuine DLL (a folder is "not empty" to the shell); Rust doesn't.
        let paths: Vec<String> = paths
            .iter()
            .filter(|p| function != "is_genuine_dll" || !Path::new(p).is_dir())
            .cloned()
            .collect();
        let bash = bash_each(d, &paths, &format!("{function} \"$line\""));
        let rust: Vec<bool> = paths.iter().map(|p| rust_fn(Path::new(p))).collect();
        assert_same(function, &paths, &bash, &rust);
    }
}

#[test]
fn oldest_backup_matches() {
    let tmp = tempfile::tempdir().unwrap();
    let d = tmp.path();
    for name in [
        "a.dll.bak.20240101_120000",
        "a.dll.bak.20230101_000000",
        "a.dll.bak.20230101_000000x",
        "a.dll.bak.old",
        "a.dll.bak",
        "a.dll.bak.2023",
        "a.dll.eax-restore.bak",
        "b.dll.bak.x_1",
        "b.dll.bak.9_9",
        "c.dll.bak.notours",
        "With Space.dll.bak.20200202_020202",
    ] {
        std::fs::write(d.join(name), b"x").unwrap();
    }
    // Only a dangling link: no backup at all.
    symlink(d.join("nowhere"), d.join("d.dll.bak.20200101_000000")).unwrap();
    let targets: Vec<String> = [
        "a.dll",
        "b.dll",
        "c.dll",
        "d.dll",
        "e.dll",
        "With Space.dll",
    ]
    .iter()
    .map(|n| d.join(n).display().to_string())
    .collect();
    std::fs::write(d.join("cases"), targets.join("\n") + "\n").unwrap();
    let out = bash(
        "while IFS= read -r line; do oldest_backup \"$line\" || printf none; echo; done < \"$1/cases\"",
        d,
    );
    let bash: Vec<&str> = out.lines().collect();
    assert_eq!(bash.len(), targets.len());
    for (target, bash) in targets.iter().zip(bash) {
        let rust = files::oldest_backup(Path::new(target))
            .map_or("none".to_string(), |p| p.display().to_string());
        assert_eq!(bash, rust, "oldest_backup {target}");
    }
}

/// Builds the same set of folders under `root`, one per case.
fn hrtf_cases(root: &Path) -> Vec<String> {
    let dir = |name: &str, files: &[&str]| {
        for f in files {
            let path = root.join(name).join(f);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, b"x").unwrap();
        }
        std::fs::create_dir_all(root.join(name)).unwrap();
    };
    dir(
        "clean",
        &[
            "HRTF/a.mhr",
            "HRTF/B.MHR",
            "HRTF/credits.txt",
            "x.json",
            "y.ini",
        ],
    );
    dir("empty", &[]);
    dir("dotfile", &[".mhr"]);
    dir("mod", &["HRTF/a.mhr", "HRTF/mod.dll"]);
    dir("noext", &["README"]);
    dir(
        "nested-mod",
        &["HRTF/deep/er/a.mhr", "HRTF/deep/er/save.dat"],
    );
    dir("has-link", &["a.mhr"]);
    symlink(root.join("clean"), root.join("has-link/link.mhr")).unwrap();
    symlink(root.join("clean"), root.join("is-link")).unwrap();
    std::fs::write(root.join("is-file"), b"x").unwrap();
    [
        "clean",
        "empty",
        "dotfile",
        "mod",
        "noext",
        "nested-mod",
        "has-link",
        "is-link",
        "is-file",
        "missing",
    ]
    .iter()
    .map(|n| root.join(n).display().to_string())
    .collect()
}

#[test]
fn remove_legacy_hrtf_dir_matches() {
    let tmp = tempfile::tempdir().unwrap();
    let (b, r) = (tmp.path().join("bash"), tmp.path().join("rust"));
    std::fs::create_dir_all(&b).unwrap();
    std::fs::create_dir_all(&r).unwrap();
    let bash_cases = hrtf_cases(&b);
    let rust_cases = hrtf_cases(&r);
    let bash = bash_each(tmp.path(), &bash_cases, "remove_legacy_hrtf_dir \"$line\"");
    let rust: Vec<bool> = rust_cases
        .iter()
        .map(|p| files::remove_legacy_hrtf_dir(Path::new(p)))
        .collect();
    assert_same("remove_legacy_hrtf_dir", &bash_cases, &bash, &rust);
    for (bp, rp) in bash_cases.iter().zip(&rust_cases) {
        assert_eq!(
            Path::new(bp).symlink_metadata().is_ok(),
            Path::new(rp).symlink_metadata().is_ok(),
            "{bp} is left or removed alike"
        );
    }
    // The link's target was never touched.
    assert!(b.join("clean").exists() == r.join("clean").exists());
}

