//! Parity with the Bash script for the manifest and file-safety helpers:
//! each case runs through the function in `src/*.sh` and through its Rust
//! port, and the answers (and the files left behind) must match.
//!
//! The uninstall's manifest reader is inline in `src/uninstall-flow.sh`, not
//! a function, so `manifest::read` is covered by its own unit tests and by
//! the checks here on each rule it applies.

use eax_restore::engine::config::{self, Reverted};
use eax_restore::engine::{files, manifest};
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};
use std::process::Command;

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("tui/ sits in the repository")
        .to_path_buf()
}

/// Runs a snippet with the script's functions loaded and returns what it
/// printed. `$1` is the folder the test works in.
fn bash(script: &str, dir: &Path) -> String {
    let full = format!(
        "for f in globals ui common cache game-config; do source \"$SRC/$f.sh\"; done\n{script}"
    );
    let out = Command::new("bash")
        .arg("-c")
        .arg(full)
        .arg("oracle")
        .arg(dir)
        .env("SRC", repo_root().join("src"))
        .env("HOME", dir)
        .env("LC_ALL", "C.UTF-8")
        .output()
        .expect("bash runs");
    assert!(
        out.status.success(),
        "the Bash snippet failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8_lossy(&out.stdout).into_owned()
}

/// Runs `test` (a shell condition on `$line`) for every line of a list and
/// returns one yes/no per line.
fn bash_each(dir: &Path, lines: &[String], test: &str) -> Vec<bool> {
    std::fs::write(dir.join("cases"), lines.join("\n") + "\n").unwrap();
    let script = format!(
        "while IFS= read -r line; do if {test}; then echo 1; else echo 0; fi; done < \"$1/cases\""
    );
    bash(&script, dir).lines().map(|l| l == "1").collect()
}

fn assert_same(what: &str, cases: &[String], bash: &[bool], rust: &[bool]) {
    assert_eq!(bash.len(), cases.len(), "{what}: Bash answered every case");
    for ((case, b), r) in cases.iter().zip(bash).zip(rust) {
        assert_eq!(b, r, "{what} {case:?}: bash says {b}, rust says {r}");
    }
}

fn strings(items: &[&str]) -> Vec<String> {
    items.iter().map(|s| s.to_string()).collect()
}

