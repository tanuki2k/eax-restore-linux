#[test]
fn manifest_writers_match() {
    let tmp = tempfile::tempdir().unwrap();
    let d = tmp.path();
    let variants = [
        ("plain", MANIFEST.to_string()),
        ("no-newline", MANIFEST.trim_end().to_string()),
        ("empty", String::new()),
        (
            "marker",
            manifest::uninstalled_marker("2026-11-13T00:00:00Z"),
        ),
    ];
    let forget = [
        "/g/Game/dsound.dll",
        "/g/Game/a [1].dll",
        // A pattern character must not match another line.
        "/g/Game/a.1.*dll",
        "VCRUN",
        "not in the file",
    ];
    for (name, text) in &variants {
        for side in ["bash", "rust"] {
            for op in ["dedupe", "forget", "forget-blank", "start", "start-keep"] {
                std::fs::write(d.join(format!("{side}-{op}-{name}")), text).unwrap();
            }
        }
        let args: Vec<String> = forget.iter().map(|f| format!("'{f}'")).collect();
        bash(
            &format!(
                "INSTALL_MANIFEST=\"$1/bash-dedupe-{name}\"; manifest_dedupe\n\
                 INSTALL_MANIFEST=\"$1/bash-forget-{name}\"; manifest_forget_paths {}\n\
                 INSTALL_MANIFEST=\"$1/bash-forget-blank-{name}\"; manifest_forget_paths ''\n\
                 start_manifest \"$1/bash-start-{name}\"; echo \"[$MANIFEST_PREV]\" > \"$1/bash-prev-{name}\"\n\
                 start_manifest \"$1/bash-start-keep-{name}\" keep; echo \"[${{MANIFEST_PREV#\"$1/bash-\"}}]\" > \"$1/bash-prevkeep-{name}\"\n\
                 if manifest_is_uninstalled \"$1/bash-dedupe-{name}\"; then echo 1; else echo 0; fi > \"$1/bash-marker-{name}\"",
                args.join(" ")
            ),
            d,
        );
        let path = |op: &str| d.join(format!("rust-{op}-{name}"));
        manifest::dedupe(&path("dedupe")).unwrap();
        let gone: Vec<Vec<u8>> = forget.iter().map(|f| f.as_bytes().to_vec()).collect();
        manifest::forget(&path("forget"), &gone).unwrap();
        manifest::forget(&path("forget-blank"), &[Vec::new()]).unwrap();
        let prev = manifest::start(&path("start"), false).unwrap();
        let prev_keep = manifest::start(&path("start-keep"), true).unwrap();

        for op in ["dedupe", "forget", "forget-blank", "start", "start-keep"] {
            let read = |side: &str| std::fs::read(d.join(format!("{side}-{op}-{name}"))).unwrap();
            assert_eq!(
                String::from_utf8_lossy(&read("bash")),
                String::from_utf8_lossy(&read("rust")),
                "{op} on the {name} manifest"
            );
            for side in ["bash", "rust"] {
                assert!(
                    !d.join(format!("{side}-{op}-{name}.tmp")).exists(),
                    "{side} left a temp file after {op}"
                );
            }
        }
        assert_eq!(prev, None);
        let bash_prev = std::fs::read_to_string(d.join(format!("bash-prev-{name}"))).unwrap();
        assert_eq!(bash_prev.trim(), "[]");
        let bash_keep = std::fs::read_to_string(d.join(format!("bash-prevkeep-{name}"))).unwrap();
        let rust_keep = prev_keep.as_ref().map_or(String::new(), |p| {
            p.file_name().unwrap().to_string_lossy()["rust-".len()..].to_string()
        });
        assert_eq!(
            bash_keep.trim(),
            format!("[{rust_keep}]"),
            "{name}: what was set aside"
        );
        if let Some(p) = &prev_keep {
            let bash_copy = d.join(format!("bash-start-keep-{name}.prev"));
            assert_eq!(std::fs::read(p).unwrap(), std::fs::read(bash_copy).unwrap());
        }
        let bash_marker = std::fs::read_to_string(d.join(format!("bash-marker-{name}"))).unwrap();
        assert_eq!(
            bash_marker.trim() == "1",
            manifest::is_uninstalled(&path("dedupe")),
            "{name}: is it the uninstalled marker"
        );
    }
}

#[test]
fn config_lines_match() {
    let tmp = tempfile::tempdir().unwrap();
    let old_names = [
        "flat_ini",
        "gas_cfg",
        "idtech_cfg",
        "dark_cfg",
        "ltx",
        "brace_cfg",
        "quoted_cfg",
        "byte_cfg",
        "lenstr_cfg",
        "gadb",
        "wine_reg",
        "ini",
        "registry",
        "toml",
        "",
    ];
    let mut lines: Vec<String> = old_names
        .iter()
        .map(|n| format!("CONFIG:audio\tEnable EAX\t/g/a b.cfg\t{n}\tSec\tkey\t__ABSENT__\tgadb"))
        .collect();
    lines.extend(strings(&[
        "CONFIG:audio\tT\t/g/a\tgadb",
        "CONFIG:audio\tT\t/g/a",
        "CONFIG:audio\tT\t/g/a\tltx\t\tk\t\t",
        "CONFIG:optional\tT\t/g/a\tini\t\tk\told value\t",
        "LAUNCHER:steam\t/f\t1\tgadb\tnew",
        "/g/Game/dsound.dll",
        "CONFIG:",
    ]));
    std::fs::write(tmp.path().join("cases"), lines.join("\n") + "\n").unwrap();
    let out = bash(
        "while IFS= read -r line; do
             upgrade_config_line \"$line\"; printf '%s\\n' \"$UPGRADED_LINE\"
             parse_config_line \"$UPGRADED_LINE\" f
             printf '<%s>' \"${f[0]-}\" \"${f[1]-}\" \"${f[2]-}\" \"${f[3]-}\" \"${f[4]-}\" \"${f[5]-}\" \"${f[6]-}\" \"${f[7]-}\"; echo
             if config_format_unreadable \"${f[3]-}\"; then echo unreadable; else echo ok; fi
         done < \"$1/cases\"",
        tmp.path(),
    );
    let mut bash = out.lines();
    for line in &lines {
        let upgraded = manifest::upgrade_config_line(line.as_bytes());
        assert_eq!(
            bash.next().unwrap().as_bytes(),
            upgraded,
            "upgrading {line:?}"
        );
        let fields = bash.next().unwrap();
        let unreadable = bash.next().unwrap() == "unreadable";
        // parse_config_line splits any line; the Rust parser only takes CONFIG: ones.
        let Some(r) = manifest::ConfigRecord::parse(&upgraded) else {
            assert!(!line.starts_with("CONFIG:"));
            continue;
        };
        let rust = format!(
            "<{}><{}><{}><{}><{}><{}><{}><{}>",
            r.category,
            r.title,
            r.path.display(),
            r.format,
            r.section,
            r.key,
            String::from_utf8_lossy(r.old.as_bytes()),
            String::from_utf8_lossy(r.new.as_bytes()),
        );
        assert_eq!(fields, rust, "the fields of {line:?}");
        assert_eq!(unreadable, r.format_unreadable(), "is {line:?} unreadable");
    }
}

/// (name, the file or none, format, section, key, old, new)
type RevertCase = (
    &'static str,
    Option<&'static str>,
    &'static str,
    &'static str,
    &'static str,
    &'static str,
    &'static str,
);

#[test]
fn reverting_a_setting_matches() {
    let tmp = tempfile::tempdir().unwrap();
    let d = tmp.path();
    let cases: [RevertCase; 12] = [
        (
            "restores",
            Some("[S]\r\nk=1\r\n"),
            "ini",
            "S",
            "k",
            "0",
            "1",
        ),
        (
            "case",
            Some("[S]\nk=TRUE\n"),
            "ini",
            "s",
            "K",
            "false",
            "true",
        ),
        (
            "removes",
            Some("[S]\nk=1\nj=2\n"),
            "ini",
            "S",
            "k",
            "__ABSENT__",
            "1",
        ),
        ("changed", Some("[S]\nk=5\n"), "ini", "S", "k", "0", "1"),
        ("gone-key", Some("[S]\nj=2\n"), "ini", "S", "k", "0", "1"),
        (
            "deleted",
            Some("[S]\nj=2\n"),
            "ini",
            "S",
            "k",
            "old",
            "__DELETE__",
        ),
        ("missing", None, "ini", "S", "k", "0", "1"),
        ("newer", Some("k=1\n"), "toml", "", "k", "0", "1"),
        ("damaged", Some("k=1\n"), "", "", "k", "0", "1"),
        (
            "flag",
            Some("; eax\neax\n"),
            "key_value",
            "",
            "eax",
            "__FALSE__",
            "__TRUE__",
        ),
        (
            "no-tag",
            Some("<A/>\n"),
            "xml_attributes",
            "Sound",
            "k",
            "0",
            "__ABSENT__",
        ),
        (
            "backslash",
            Some("[S]\nk=1\n"),
            "ini",
            "S",
            "k",
            "C:\\old\\new",
            "1",
        ),
    ];
    let mut script = String::from(
        "wine_registry_quiet() { return 0; }\nprint_status() { :; }\nprint_warning_arrow() { :; }\nprint_error_arrow() { :; }\n",
    );
    let mut rust = Vec::new();
    for (name, file, format, sec, key, old, new) in cases {
        let (bf, rf) = (
            d.join(format!("bash-{name}")),
            d.join(format!("rust-{name}")),
        );
        if let Some(text) = file {
            std::fs::write(&bf, text).unwrap();
            std::fs::write(&rf, text).unwrap();
        }
        let line = |f: &Path| {
            format!(
                "CONFIG:audio\tTitle\t{}\t{format}\t{sec}\t{key}\t{old}\t{new}",
                f.display()
            )
        };
        std::fs::write(d.join(format!("line-{name}")), line(&bf)).unwrap();
        script.push_str(&format!(
            "GAME_SETTINGS_KEPT=(); GAME_SETTINGS_REVERT_GROUPS=(\"audio\"$'\\x1f'\"Title\"$'\\x1f'\"$(cat \"$1/line-{name}\")\")\n\
             revert_game_settings; echo \"${{#GAME_SETTINGS_KEPT[@]}}\"\n"
        ));
        let record = manifest::ConfigRecord::parse(line(&rf).as_bytes()).unwrap();
        rust.push((name, config::revert(&record, &mut || true)));
    }
    let out = bash(&script, d);
    let kept: Vec<&str> = out.lines().collect();
    assert_eq!(kept.len(), cases.len(), "{out}");
    for ((name, outcome), kept) in rust.iter().zip(kept) {
        assert_eq!(
            kept == "1",
            outcome.keeps_record(),
            "{name}: Bash kept {kept} record(s), Rust said {outcome:?}"
        );
        let read = |side: &str| std::fs::read(d.join(format!("{side}-{name}"))).ok();
        assert_eq!(read("bash"), read("rust"), "{name}: the file afterwards");
    }
    let outcome = |name: &str| rust.iter().find(|(n, _)| *n == name).unwrap().1;
    assert_eq!(outcome("restores"), Reverted::Restored);
    assert_eq!(outcome("changed"), Reverted::ChangedSince);
    assert_eq!(outcome("missing"), Reverted::Nothing);
    assert_eq!(outcome("newer"), Reverted::Unreadable);
    assert_eq!(outcome("no-tag"), Reverted::Failed);
}
